// ─── Test 8: kebab-to-PascalCase conversion ────────────────────────

describe('generateDraft — PascalCase conversion', () => {
  it('converts kebab-case flowId to PascalCase test class name', () => {
    const flow = makeBasicTapFlow({ flowId: 'user-login-flow' });
    const result = generateDraft(flow, { format: 'xcuitest', runId: 'run-014' });

    expect(result.code).toContain('UserLoginFlowTests');
    // The header naturally contains the flowId; verify the class name uses PascalCase
    expect(result.code).toContain('class UserLoginFlowTests');
    expect(result.code).not.toContain('class user-login-flow');
  });

  it('handles multi-segment kebab-case', () => {
    const flow = makeBasicTapFlow({ flowId: 'deep-link-navigation-test' });
    const result = generateDraft(flow, { format: 'xcuitest', runId: 'run-015' });

    expect(result.code).toContain('DeepLinkNavigationTestTests');
  });

  it('handles single-word flowId', () => {
    const flow = makeBasicTapFlow({ flowId: 'smoke' });
    const result = generateDraft(flow, { format: 'xcuitest', runId: 'run-016' });

    expect(result.code).toContain('SmokeTests');
  });

  it('handles already PascalCase (no change needed)', () => {
    const flow = makeBasicTapFlow({ flowId: 'LoginTest' });
    const result = generateDraft(flow, { format: 'xcuitest', runId: 'run-017' });

    expect(result.code).toContain('LoginTestTests');
  });

  it('uses PascalCase in Appium describe block', () => {
    const flow = makeBasicTapFlow({ flowId: 'login-smoke-test' });
    const result = generateDraft(flow, { format: 'appium', runId: 'run-018' });

    // Appium describe should use PascalCase for the block name
    expect(result.code).toContain("describe('LoginSmokeTest'");
  });
});

