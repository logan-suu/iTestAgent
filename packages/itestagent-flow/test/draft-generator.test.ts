// ─── Test 5: Missing locator generates placeholder comment (R5) ────

describe('generateDraft — missing locator (R5)', () => {
  it('generates placeholder when locator is missing in XCUITest', () => {
    const flow = makeBasicTapFlow({
      steps: [{ action: 'tap', target: 'Mystery Button' }],
    });
    const result = generateDraft(flow, { format: 'xcuitest', runId: 'run-007' });

    expect(result.code).toContain('DRAFT: locator missing');
    expect(result.code).toContain('Mystery Button');
  });

  it('generates placeholder when locator is missing in Appium', () => {
    const flow = makeBasicTapFlow({
      steps: [{ action: 'tap', target: 'Mystery Button' }],
    });
    const result = generateDraft(flow, { format: 'appium', runId: 'run-008' });

    expect(result.code).toContain('DRAFT: locator missing');
    expect(result.code).toContain('Mystery Button');
  });

  it('never fabricates a locator value when locator is undefined (R5)', () => {
    const flow = makeBasicTapFlow({
      steps: [{ action: 'tap', target: 'Unknown' }],
    });
    const result = generateDraft(flow, { format: 'xcuitest', runId: 'run-009' });

    // Should NOT contain any auto-generated accessibility identifier
    // The placeholder should use the target name but explicitly mark as draft
    expect(result.code).toContain('DRAFT');
    expect(result.code).toContain('Unknown');
    // Should not fabricate a made-up accessibilityId like "unknown_btn"
    expect(result.code).not.toContain('matching(identifier: "Unknown")');
  });
});

