// ─── Test 1: XCUITest generation with basic tap flow ──────────────

describe('generateDraft — XCUITest', () => {
  it('generates XCUITest class with header, setUp, tearDown, and test method', () => {
    const flow = makeBasicTapFlow();
    const result = generateDraft(flow, { format: 'xcuitest', runId: 'run-001' });

    // Header
    expect(result.code).toContain('⚠️  DRAFT — EXPERIMENTAL');
    expect(result.code).toContain('Generated by iTestAgent');
    expect(result.code).toContain('Generated from Flow: login-smoke-test');
    expect(result.code).toContain('Run ID: run-001');

    // Core XCUITest imports and class
    expect(result.code).toContain('import XCTest');
    expect(result.code).toContain('XCTestCase');
    expect(result.code).toContain('LoginSmokeTestTests');
    expect(result.code).toContain('func setUp');
    expect(result.code).toContain('func tearDown');
    expect(result.code).toContain('func test');

    // Language and metadata
    expect(result.language).toBe('swift');
    expect(result.flowId).toBe('login-smoke-test');
    expect(result.runId).toBe('run-001');

    // Steps mapped
    expect(result.code).toContain('launch()');
    expect(result.code).toContain('login_btn');
    expect(result.code).toContain('sleep');
  });
});

